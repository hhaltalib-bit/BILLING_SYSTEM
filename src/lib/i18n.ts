export function translateArabic(arabic: string, lang: 'ar' | 'en'): string {
  if (lang === 'ar') return arabic
  return pageTranslations[arabic]?.en ?? arabic
}

export function useT() {
  const lang = useAppStore((s) => s.lang)
  return function t(arabic: string): string {
    return translateArabic(arabic, lang)
  }
}
